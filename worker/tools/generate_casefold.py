"""Emit the deterministic full Unicode 14.0.0 case-folding table for the Worker."""

import json
import sys
import unicodedata


def main() -> None:
    if (sys.implementation.name != "cpython" or sys.version_info[:2] != (3, 11)
            or unicodedata.unidata_version != "14.0.0"):
        raise SystemExit("Case-folding generation requires CPython 3.11 and Unicode 14.0.0.")

    print("// Generated by tools/generate_casefold.py from CPython 3.11 / Unicode 14.0.0.")
    print("// Unicode character data copyright 2021 Unicode, Inc. https://www.unicode.org/license.txt")
    print("export const FULL_CASE_FOLD: Readonly<Record<string, string>> = {")
    for point in range(0x110000):
        if 0xD800 <= point <= 0xDFFF:
            continue
        scalar = chr(point)
        folded = scalar.casefold()
        if folded != scalar:
            print(f"  {json.dumps(scalar)}: {json.dumps(folded)},")
    print("};")


if __name__ == "__main__":
    main()
